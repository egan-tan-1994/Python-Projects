# --------------------------------------------------------------------------
# Phase 19 helper: safe annualized performance metrics
# --------------------------------------------------------------------------
def phase19_metrics_from_returns(
        returns_series,
        risk_free=phase19_base_risk_free):

    series = pd.Series(returns_series, dtype=float).dropna()

    if series.empty:
        return {
            "Annualized Return": np.nan,
            "Annualized Volatility": np.nan,
            "Sharpe Ratio": np.nan,
            "Sortino Ratio": np.nan,
            "Maximum Drawdown": np.nan,
            "Calmar Ratio": np.nan,
            "VaR 95%": np.nan,
            "CVaR 95%": np.nan,
            "Terminal Growth": np.nan
        }

    growth = (1.0 + series).cumprod()
    terminal_growth = growth.iloc[-1]

    annualized_return = (
        terminal_growth ** (252.0 / len(series)) - 1.0
    )

    annualized_volatility = (
        series.std() * np.sqrt(252.0)
    )

    if np.isfinite(annualized_volatility) and annualized_volatility > 0:
        sharpe_ratio = (
            annualized_return - risk_free
        ) / annualized_volatility
    else:
        sharpe_ratio = np.nan

    downside = series[series < 0]

    if len(downside) > 1:
        downside_volatility = (
            downside.std() * np.sqrt(252.0)
        )
    else:
        downside_volatility = np.nan

    if np.isfinite(downside_volatility) and downside_volatility > 0:
        sortino_ratio = (
            annualized_return - risk_free
        ) / downside_volatility
    else:
        sortino_ratio = np.nan

    running_max = growth.cummax()
    drawdown = (growth / running_max) - 1.0
    maximum_drawdown = drawdown.min()

    if np.isfinite(maximum_drawdown) and maximum_drawdown != 0:
        calmar_ratio = (
            annualized_return / abs(maximum_drawdown)
        )
    else:
        calmar_ratio = np.nan

    var_95 = np.percentile(series, 5)
    cvar_95 = series[series <= var_95].mean()

    return {
        "Annualized Return": annualized_return,
        "Annualized Volatility": annualized_volatility,
        "Sharpe Ratio": sharpe_ratio,
        "Sortino Ratio": sortino_ratio,
        "Maximum Drawdown": maximum_drawdown,
        "Calmar Ratio": calmar_ratio,
        "VaR 95%": var_95,
        "CVaR 95%": cvar_95,
        "Terminal Growth": terminal_growth
    }


# --------------------------------------------------------------------------
# Phase 19 helper: risk-parity optimizer with explicit maximum-weight input
# --------------------------------------------------------------------------
def phase19_risk_parity_weights(covariance_matrix, maximum_weight):

    covariance_values = np.asarray(covariance_matrix, dtype=float)
    n_assets = covariance_values.shape[0]

    if covariance_values.shape != (n_assets, n_assets):
        raise ValueError("Risk-Parity covariance matrix must be square.")

    def portfolio_volatility_local(weights):
        variance = (
            weights.T @ covariance_values @ weights
        )
        return np.sqrt(max(float(variance), 0.0))

    def risk_contribution_local(weights):
        sigma = portfolio_volatility_local(weights)
        if sigma <= 0:
            return np.zeros_like(weights)
        marginal = (covariance_values @ weights) / sigma
        return weights * marginal

    def objective_local(weights):
        rc = risk_contribution_local(weights)
        target_rc = rc.sum() / len(weights)
        return float(np.sum((rc - target_rc) ** 2))

    constraints_local = {
        "type": "eq",
        "fun": lambda weights: np.sum(weights) - 1.0
    }

    bounds_local = tuple(
        (0.0, maximum_weight)
        for _ in range(n_assets)
    )

    initial_guess_local = np.repeat(
        1.0 / n_assets,
        n_assets
    )

    result = minimize(
        objective_local,
        initial_guess_local,
        method="SLSQP",
        constraints=constraints_local,
        bounds=bounds_local,
        options={
            "maxiter": 2000,
            "ftol": 1e-10
        }
    )

    if not result.success:
        raise RuntimeError(
            "Phase 19 Risk-Parity optimization failed: "
            f"{result.message}"
        )

    weights = pd.Series(
        result.x,
        index=phase19_assets,
        dtype=float
    )

    if not np.isclose(weights.sum(), 1.0):
        weights /= weights.sum()

    return weights


# --------------------------------------------------------------------------
# Phase 19 helper: model-specific optimizer with explicit parameters
# --------------------------------------------------------------------------
def phase19_optimize_weights(
        model_name,
        calibration_end,
        lookback_window_value,
        maximum_weight_value,
        risk_free_value,
        mc_simulations_value,
        seed_value):

    calibration_end = pd.Timestamp(calibration_end)

    price_history = phase19_prices.loc[:calibration_end].copy()

    # +1 is needed because PyPortfolioOpt's return calculations require the
    # first price observation to produce the first return observation.
    if len(price_history) < lookback_window_value + 1:
        raise ValueError(
            f"Insufficient price history for {model_name}: "
            f"need {lookback_window_value + 1} observations, "
            f"found {len(price_history)}."
        )

    window_prices = price_history.tail(
        lookback_window_value + 1
    )

    window_mu = expected_returns.mean_historical_return(
        window_prices
    ).reindex(phase19_assets)

    window_S = phase17_estimate_covariance(
        window_prices,
        phase19_covariance_model
    ).reindex(
        index=phase19_assets,
        columns=phase19_assets
    )

    if model_name == "Equal-Weight":

        weights = pd.Series(
            np.repeat(
                1.0 / len(phase19_assets),
                len(phase19_assets)
            ),
            index=phase19_assets,
            dtype=float
        )

    elif model_name == "Simulated (Max Sharpe Ratio)":

        weights = phase17_monte_carlo_max_sharpe(
            expected_returns_window=window_mu,
            covariance_window=window_S,
            simulations=int(mc_simulations_value),
            risk_free=risk_free_value,
            maximum_weight=maximum_weight_value,
            seed=int(seed_value)
        )

    elif model_name == "Markowitz":

        ef = EfficientFrontier(
            expected_returns=window_mu,
            cov_matrix=window_S,
            weight_bounds=(0.0, maximum_weight_value)
        )

        if optimization_method == "max_sharpe":
            ef.max_sharpe(
                risk_free_rate=risk_free_value
            )
        elif optimization_method == "min_volatility":
            ef.min_volatility()
        elif optimization_method == "efficient_risk":
            ef.efficient_risk(target_volatility)
        elif optimization_method == "efficient_return":
            ef.efficient_return(target_return)
        elif optimization_method == "max_quadratic_utility":
            ef.max_quadratic_utility(
                risk_aversion=risk_aversion
            )
        else:
            raise ValueError(
                f"Unknown optimization method: {optimization_method}"
            )

        weights = pd.Series(
            ef.clean_weights(),
            dtype=float
        ).reindex(phase19_assets)

    elif model_name == "Black-Litterman":

        caps_history = (
            market_caps
            .reindex(columns=phase19_assets)
            .sort_index()
        )

        caps_history = caps_history.loc[
            caps_history.index <= calibration_end
        ]

        if caps_history.empty:
            raise ValueError(
                "No historical market-cap data available for "
                f"{calibration_end.date()}."
            )

        caps_history = caps_history.ffill()
        market_caps_at_date = caps_history.iloc[-1]

        if market_caps_at_date.isna().any():
            missing = market_caps_at_date[
                market_caps_at_date.isna()
            ].index.tolist()
            raise ValueError(
                "Missing market-cap data for "
                f"{missing} at {calibration_end.date()}."
            )

        benchmark_window = (
            prices[benchmark_ticker]
            .loc[:calibration_end]
            .tail(lookback_window_value + 1)
        )

        if len(benchmark_window) < 20:
            raise ValueError(
                "Insufficient benchmark data for Black-Litterman."
            )

        delta_value = market_implied_risk_aversion(
            benchmark_window
        )

        prior_returns = market_implied_prior_returns(
            market_caps=market_caps_at_date,
            risk_aversion=delta_value,
            cov_matrix=window_S
        ).reindex(phase19_assets)

        rolling_views = {
            ticker: absolute_views[ticker]
            for ticker in absolute_views
            if ticker in phase19_assets
        }

        rolling_confidences = np.array(
            [
                view_confidences[ticker]
                for ticker in rolling_views
            ],
            dtype=float
        )

        bl_model = BlackLittermanModel(
            window_S,
            pi=prior_returns,
            absolute_views=rolling_views,
            omega="idzorek",
            view_confidences=rolling_confidences
        )

        bl_returns_window = bl_model.bl_returns().reindex(
            phase19_assets
        )

        bl_covariance_window = bl_model.bl_cov().reindex(
            index=phase19_assets,
            columns=phase19_assets
        )

        ef_bl = EfficientFrontier(
            bl_returns_window,
            bl_covariance_window,
            weight_bounds=(0.0, maximum_weight_value)
        )

        if optimization_method == "max_sharpe":
            ef_bl.max_sharpe(
                risk_free_rate=risk_free_value
            )
        elif optimization_method == "min_volatility":
            ef_bl.min_volatility()
        elif optimization_method == "efficient_risk":
            ef_bl.efficient_risk(target_volatility)
        elif optimization_method == "efficient_return":
            ef_bl.efficient_return(target_return)
        elif optimization_method == "max_quadratic_utility":
            ef_bl.max_quadratic_utility(
                risk_aversion=risk_aversion
            )
        else:
            raise ValueError(
                f"Unknown optimization method: {optimization_method}"
            )

        weights = pd.Series(
            ef_bl.clean_weights(),
            dtype=float
        ).reindex(phase19_assets)

    elif model_name == "Risk-Parity":

        weights = phase19_risk_parity_weights(
            window_S,
            maximum_weight_value
        )

    else:
        raise ValueError(
            f"Unknown Phase 19 model: {model_name}"
        )

    if weights.isna().any():
        missing = weights[weights.isna()].index.tolist()
        raise ValueError(
            f"{model_name} produced missing weights: {missing}"
        )

    weights = weights.astype(float)

    if not np.isfinite(weights.values).all():
        raise ValueError(
            f"{model_name} produced non-finite weights."
        )

    if (weights < -1e-12).any():
        raise ValueError(
            f"{model_name} produced negative weights unexpectedly."
        )

    # Equal weight is intentionally allowed to exceed the scenario maximum
    # when the universe is smaller than 1 / maximum_weight. For this project's
    # 50-asset universe that condition does not occur.
    if model_name != "Equal-Weight" and weights.max() > \
    maximum_weight_value + 1e-6:
        raise ValueError(
            f"{model_name} exceeded the maximum-weight constraint."
        )

    weight_sum = weights.sum()

    if weight_sum <= 0:
        raise ValueError(
            f"{model_name} produced a non-positive weight sum."
        )

    if not np.isclose(weight_sum, 1.0):
        weights /= weight_sum

    return weights


# --------------------------------------------------------------------------
# Phase 19 helper: validation-period backtest with initial transaction cost
# --------------------------------------------------------------------------
def phase19_validate_weights(
        weights,
        validation_returns,
        risk_free_value,
        transaction_cost_rate_value):

    validation_returns = validation_returns.loc[
        :, phase19_assets
    ].copy()

    gross_daily_returns = (
        validation_returns @ weights
    )

    initial_turnover = float(
        weights.abs().sum()
    )

    initial_cost_rate = (
        initial_turnover * transaction_cost_rate_value
    )

    # Initial deployment cost is deducted before the first validation return.
    net_growth = (
        (1.0 - initial_cost_rate) *
        (1.0 + gross_daily_returns)
    )

    net_daily_returns = net_growth - 1.0

    metrics = phase19_metrics_from_returns(
        net_daily_returns,
        risk_free=risk_free_value
    )

    metrics["Gross Return"] = (
        (1.0 + gross_daily_returns).prod()
        ** (252.0 / len(gross_daily_returns))
        - 1.0
    )

    metrics["Initial Turnover"] = initial_turnover
    metrics["Initial Transaction Cost Rate"] = initial_cost_rate
    metrics["Validation Days"] = len(validation_returns)
    metrics["Final Value per $1"] = (
        (1.0 + net_daily_returns).prod()
    )

    return metrics, gross_daily_returns, net_daily_returns


