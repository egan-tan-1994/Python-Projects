def phase17_weight_diagnostics(
        weights,
        previous_weights=None):

    weights = weights.reindex(
        phase17_assets
    ).fillna(0.0)

    hhi = np.sum(
        weights.values ** 2
    )

    effective_holdings = (
        1.0 / hhi
        if hhi > 0
        else np.nan
    )

    active_holdings = (
        (weights.abs() > 0.01).sum()
    )

    max_weight_value = (
        weights.max()
    )

    min_weight_value = (
        weights.min()
    )

    if previous_weights is None:

        allocation_change = (
            weights.abs().sum()
        )

    else:

        previous_weights = (
            previous_weights
            .reindex(phase17_assets)
            .fillna(0.0)
        )

        allocation_change = (
            np.abs(
                weights -
                previous_weights
            ).sum()
        )

    return {
        "HHI": hhi,
        "Effective Number of Holdings":
            effective_holdings,
        "Active Holdings (>1%)":
            active_holdings,
        "Maximum Weight":
            max_weight_value,
        "Minimum Weight":
            min_weight_value,
        "Allocation Change (L1)":
            allocation_change
    }


