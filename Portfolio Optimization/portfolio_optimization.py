# --------------------------------------------------------------------------
# Factor exposure regression
# --------------------------------------------------------------------------
def phase20_regress_factor_exposure(
        portfolio_series,
        factor_frame,
        risk_free_daily):

    y = pd.Series(portfolio_series, dtype=float).rename("Portfolio")
    factors = factor_frame.copy()

    joined = pd.concat(
        [y, factors],
        axis=1,
        join="inner"
    ).dropna()

    if len(joined) < phase20_min_regression_observations:
        return None

    factor_columns = list(factors.columns)
    y_excess = (
        joined["Portfolio"] - risk_free_daily
    ).to_numpy(dtype=float)

    X_factors = joined[factor_columns].to_numpy(dtype=float)
    X = np.column_stack(
        [np.ones(len(X_factors)), X_factors]
    )

    coefficients, *_ = np.linalg.lstsq(
        X,
        y_excess,
        rcond=None
    )

    alpha_daily = float(coefficients[0])
    betas = coefficients[1:]

    fitted = X @ coefficients
    residuals = y_excess - fitted

    total_variance = float(np.var(y_excess, ddof=1))
    residual_variance = float(np.var(residuals, ddof=1))

    if total_variance > 0:
        r_squared = 1.0 - residual_variance / total_variance
    else:
        r_squared = np.nan

    covariance_matrix = np.cov(
        X_factors,
        y_excess,
        rowvar=False,
        ddof=1
    )
    factor_covariance = covariance_matrix[:-1, -1]

    factor_risk_contribution = (
        betas * factor_covariance
    )

    total_explained_risk = float(
        factor_risk_contribution.sum()
    )

    factor_rows = []

    for index, factor_name in enumerate(factor_columns):
        contribution = float(
            factor_risk_contribution[index]
        )

        factor_rows.append({
            "Factor": factor_name,
            "Beta": float(betas[index]),
            "Factor Volatility": (
                joined[factor_name].std() * np.sqrt(252.0)
            ),
            "Factor Mean Return": (
                joined[factor_name].mean() * 252.0
            ),
            "Covariance With Portfolio Excess Return": (
                factor_covariance[index]
            ),
            "Variance Contribution": contribution,
            "Risk Contribution %": (
                contribution / total_variance
                if total_variance > 0
                else np.nan
            )
        })

    factor_rows.append({
        "Factor": "Residual",
        "Beta": np.nan,
        "Factor Volatility": (
            np.std(residuals, ddof=1) * np.sqrt(252.0)
        ),
        "Factor Mean Return": np.mean(residuals) * 252.0,
        "Covariance With Portfolio Excess Return": np.nan,
        "Variance Contribution": residual_variance,
        "Risk Contribution %": (
            residual_variance / total_variance
            if total_variance > 0
            else np.nan
        )
    })

    # The sum of factor and residual variance contributions should equal total
    # variance up to numerical error.
    alpha_annualized = (
        (1.0 + alpha_daily) ** 252.0 - 1.0
    )

    return {
        "Observations": len(joined),
        "Daily Alpha": alpha_daily,
        "Annualized Alpha": alpha_annualized,
        "R-Squared": r_squared,
        "Residual Volatility": (
            np.std(residuals, ddof=1) * np.sqrt(252.0)
        ),
        "Total Excess Return Volatility": (
            np.std(y_excess, ddof=1) * np.sqrt(252.0)
        ),
        "Factor Risk Rows": factor_rows
    }


