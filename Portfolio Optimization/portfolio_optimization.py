        valid = signal.dropna()
        if len(valid) < 2 * n_count:
            return np.nan

        ranked = valid.sort_values(ascending=ascending)
        low_group = ranked.index[:n_count]
        high_group = ranked.index[-n_count:]

        low_return = returns_today.reindex(low_group).mean()
        high_return = returns_today.reindex(high_group).mean()

        return float(low_return - high_return)

