def phase18_get_weights(
        rebalance_date,
        model_name):

    key = (
        rebalance_date,
        model_name
    )

    if key not in phase18_weight_matrix.index:

        raise KeyError(
            f"No Phase 17 allocation found for "
            f"{model_name} on {rebalance_date}."
        )

    weights = (
        phase18_weight_matrix
        .loc[key]
        .astype(float)
        .reindex(phase18_assets)
    )

    if weights.isna().any():

        missing = (
            weights[
                weights.isna()
            ].index.tolist()
        )

        raise ValueError(
            f"{model_name} has missing weights on "
            f"{rebalance_date}: {missing}"
        )

    if not np.isfinite(
            weights.values
    ).all():

        raise ValueError(
            f"{model_name} has non-finite "
            f"weights on {rebalance_date}."
        )

    weight_sum = weights.sum()

    if weight_sum <= 0:

        raise ValueError(
            f"{model_name} has non-positive "
            f"weight sum on {rebalance_date}."
        )

    weights = (
        weights / weight_sum
    )

    return weights


# ============================================================================
# Helper: portfolio performance metrics
# ============================================================================

def phase18_calculate_metrics(
        returns,
        initial_capital_value,
        final_portfolio_value,
        total_turnover_value,
        total_transaction_cost_value,
        benchmark_returns=None):

    returns = (
        pd.Series(
            returns,
            dtype=float
        )
        .dropna()
    )

    if returns.empty:

        return {
            "Initial Capital":
                initial_capital_value,

            "Final Portfolio Value":
                np.nan,

            "Total Return":
                np.nan,

            "Annualized Return":
                np.nan,

            "Annualized Volatility":
                np.nan,

            "Sharpe Ratio":
                np.nan,

            "Sortino Ratio":
                np.nan,

            "Maximum Drawdown":
                np.nan,

            "Calmar Ratio":
                np.nan,

            "VaR (95%)":
                np.nan,

            "CVaR (95%)":
                np.nan,

            "Total Turnover":
                total_turnover_value,

            "Total Transaction Cost":
                total_transaction_cost_value
        }

    growth = (
        1.0 + returns
    ).cumprod()

    final_growth = (
        growth.iloc[-1]
    )

    total_return = (
        final_growth - 1.0
    )

    annualized_return = (
        final_growth
        ** (
            252.0 /
            len(returns)
        )
        - 1.0
    )

    annualized_volatility = (
        returns.std() *
        np.sqrt(252.0)
    )

    if (
        np.isfinite(
            annualized_volatility
        )
        and annualized_volatility > 0
    ):

        sharpe_ratio = (
            (
                annualized_return -
                phase18_risk_free_rate
            )
            /
            annualized_volatility
        )

    else:

        sharpe_ratio = np.nan

    downside_returns = (
        returns[
            returns < 0
        ]
    )

    if len(downside_returns) > 1:

        downside_volatility = (
            downside_returns.std() *
            np.sqrt(252.0)
        )

    else:

        downside_volatility = np.nan

    if (
        np.isfinite(
            downside_volatility
        )
        and downside_volatility > 0
    ):

        sortino_ratio = (
            (
                annualized_return -
                phase18_risk_free_rate
            )
            /
            downside_volatility
        )

    else:

        sortino_ratio = np.nan

    running_max = (
        growth.cummax()
    )

    drawdown = (
        growth /
        running_max
    ) - 1.0

    maximum_drawdown = (
        drawdown.min()
    )

    if (
        np.isfinite(maximum_drawdown)
        and maximum_drawdown != 0
    ):

        calmar_ratio = (
            annualized_return /
            abs(maximum_drawdown)
        )

    else:

        calmar_ratio = np.nan

    var_95 = np.percentile(
        returns,
        5
    )

    cvar_95 = (
        returns[
            returns <= var_95
        ].mean()
    )

    metrics = {

        "Initial Capital":
            initial_capital_value,

        "Final Portfolio Value":
            final_portfolio_value,

        "Total Return":
            total_return,

        "Annualized Return":
            annualized_return,

        "Annualized Volatility":
            annualized_volatility,

        "Sharpe Ratio":
            sharpe_ratio,

        "Sortino Ratio":
            sortino_ratio,

        "Maximum Drawdown":
            maximum_drawdown,

        "Calmar Ratio":
            calmar_ratio,

        "VaR (95%)":
            var_95,

        "CVaR (95%)":
            cvar_95,

        "Total Turnover":
            total_turnover_value,

        "Total Transaction Cost":
            total_transaction_cost_value
    }

    # ------------------------------------------------------------
    # Benchmark-relative statistics
    # ------------------------------------------------------------

    if benchmark_returns is not None:

        aligned = pd.concat(
            [
                returns.rename("Portfolio"),
                benchmark_returns.rename("Benchmark")
            ],
            axis=1
        ).dropna()

        if len(aligned) > 1:

            portfolio_excess = (
                aligned["Portfolio"] -
                phase18_risk_free_rate / 252.0
            )

            benchmark_excess = (
                aligned["Benchmark"] -
                phase18_risk_free_rate / 252.0
            )

            benchmark_variance = (
                benchmark_excess.var()
            )

            if (
                np.isfinite(
                    benchmark_variance
                )
                and benchmark_variance > 0
            ):

                beta = (
                    portfolio_excess
                    .cov(benchmark_excess)
                    /
                    benchmark_variance
                )

            else:

                beta = np.nan

            benchmark_annualized_return = (
                (
                    1.0 +
                    aligned["Benchmark"]
                ).prod()
                **
                (
                    252.0 /
                    len(aligned)
                )
                - 1.0
            )

            annualized_alpha = (
                annualized_return -
                (
                    phase18_risk_free_rate +
                    beta *
                    (
                        benchmark_annualized_return -
                        phase18_risk_free_rate
                    )
                )
            )

            tracking_error = (
                (
                    aligned["Portfolio"] -
                    aligned["Benchmark"]
                ).std()
                *
                np.sqrt(252.0)
            )

            if (
                np.isfinite(tracking_error)
                and tracking_error > 0
            ):

                information_ratio = (
                    (
                        annualized_return -
                        benchmark_annualized_return
                    )
                    /
                    tracking_error
                )

            else:

                information_ratio = np.nan

            correlation = (
                aligned["Portfolio"]
                .corr(
                    aligned["Benchmark"]
                )
            )

            up_days = (
                aligned["Benchmark"] > 0
            )

            down_days = (
                aligned["Benchmark"] < 0
            )

            if up_days.any():

                upside_capture = (
                    (
                        aligned.loc[
                            up_days,
                            "Portfolio"
                        ].mean()
                    )
                    /
                    aligned.loc[
                        up_days,
                        "Benchmark"
                    ].mean()
                )

            else:

                upside_capture = np.nan

            if down_days.any():

                downside_capture = (
                    (
                        aligned.loc[
                            down_days,
                            "Portfolio"
                        ].mean()
                    )
                    /
                    aligned.loc[
                        down_days,
                        "Benchmark"
                    ].mean()
                )

            else:

                downside_capture = np.nan

            metrics.update({

                "Benchmark Return":
                    benchmark_annualized_return,

                "Alpha":
                    annualized_alpha,

                "Beta":
                    beta,

                "Correlation":
                    correlation,

                "Tracking Error":
                    tracking_error,

                "Information Ratio":
                    information_ratio,

                "Upside Capture":
                    upside_capture,

                "Downside Capture":
                    downside_capture
            })

    return metrics


