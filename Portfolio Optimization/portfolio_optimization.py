# --------------------------------------------------------------------------
# Baseline asset risk decomposition using the project's selected covariance.
# --------------------------------------------------------------------------
def phase20_euler_risk_decomposition(
        weights,
        covariance_matrix,
        model_name):

    w = phase20_normalize_weights(weights).to_numpy(dtype=float)
    covariance = (
        pd.DataFrame(covariance_matrix)
        .reindex(index=phase20_assets, columns=phase20_assets)
        .to_numpy(dtype=float)
    )

    portfolio_variance = float(
        w.T @ covariance @ w
    )

    if portfolio_variance <= 0:
        return pd.DataFrame()

    portfolio_volatility = np.sqrt(
        portfolio_variance
    )

    marginal_risk = (
        covariance @ w
    ) / portfolio_volatility

    component_risk = w * marginal_risk
    component_variance = w * (covariance @ w)
    risk_percentage = component_variance / portfolio_variance

    records = []

    for index, ticker in enumerate(phase20_assets):
        records.append({
            "Model": model_name,
            "Ticker": ticker,
            "Weight": w[index],
            "Marginal Risk Contribution": marginal_risk[index],
            "Component Risk": component_risk[index],
            "Component Variance": component_variance[index],
            "Risk Contribution %": risk_percentage[index],
            "Portfolio Volatility": portfolio_volatility
        })

    return pd.DataFrame(records)


