# --------------------------------------------------------------------------
# Helper: robust portfolio weight normalization
# --------------------------------------------------------------------------
def phase20_normalize_weights(weights):
    series = pd.Series(weights, dtype=float).reindex(phase20_assets)

    if series.isna().any():
        missing = series[series.isna()].index.tolist()
        raise ValueError(
            f"Phase 20 weights are missing assets: {missing}"
        )

    if not np.isfinite(series.values).all():
        raise ValueError(
            "Phase 20 weights contain non-finite values."
        )

    total = float(series.sum())
    if total <= 0:
        raise ValueError(
            "Phase 20 weights have a non-positive total."
        )

    return series / total


# --------------------------------------------------------------------------
# Reconstruct daily active weights and asset-level contribution
# --------------------------------------------------------------------------
def phase20_reconstruct_model(
        model_name,
        model_daily_results,
        asset_returns):

    model_daily_results = (
        model_daily_results
        .sort_values("Date")
        .set_index("Date")
    )

    dates = pd.DatetimeIndex(model_daily_results.index)
    if dates.empty:
        return pd.DataFrame(), pd.DataFrame()

    # The allocation estimated at date t is active starting on the next
    # trading day. Therefore the initial OOS allocation must be the most
    # recent rebalance strictly before the first OOS return date.
    usable_rebalances = phase20_rebalance_dates[
        phase20_rebalance_dates < dates.min()
    ]

    if len(usable_rebalances) == 0:
        raise RuntimeError(
            f"No Phase 17 allocation was available for {model_name}."
        )

    # Phase 18 target allocations are stored in rolling_weights_panel.
    target_matrix = (
        rolling_weights_panel
        .copy()
        .reindex(columns=phase20_assets)
    )

    # Find the first target allocation used for this OOS period.
    first_target_date = usable_rebalances[-1]
    target_key = (first_target_date, model_name)

    if target_key not in target_matrix.index:
        # Fallback to the most recent available target before the first OOS date.
        candidate_dates = [
            d for d in phase20_rebalance_dates
            if d < dates.min()
            and (d, model_name) in target_matrix.index
        ]
        if not candidate_dates:
            raise RuntimeError(
                f"No target allocation found for {model_name}."
            )
        first_target_date = candidate_dates[-1]
        target_key = (first_target_date, model_name)

    current_weights = phase20_normalize_weights(
        target_matrix.loc[target_key]
    )

    contribution_records = []
    weight_records = []

    # A target allocation dated t becomes active on the next trading day.
    for date in dates:
        date_returns = asset_returns.loc[date].reindex(phase20_assets)
        date_returns = date_returns.fillna(0.0).astype(float)

        pre_trade_weights = current_weights.copy()

        asset_contributions = (
            pre_trade_weights * date_returns
        )

        gross_return = float(asset_contributions.sum())

        for ticker in phase20_assets:
            contribution_records.append({
                "Date": date,
                "Model": model_name,
                "Ticker": ticker,
                "Weight": pre_trade_weights.loc[ticker],
                "Asset Return": date_returns.loc[ticker],
                "Gross Contribution": asset_contributions.loc[ticker]
            })

        for ticker in phase20_assets:
            weight_records.append({
                "Date": date,
                "Model": model_name,
                "Ticker": ticker,
                "Weight": pre_trade_weights.loc[ticker]
            })

        # Drift weights after the day's asset returns.
        drifted_values = (
            pre_trade_weights * (1.0 + date_returns)
        )
        drifted_total = float(drifted_values.sum())

        if drifted_total <= 0:
            raise RuntimeError(
                f"Non-positive drifted portfolio value for {model_name} "
                f"on {date.date()}."
            )

        current_weights = drifted_values / drifted_total

        # A rebalance occurring on date becomes active NEXT trading day.
        if date in phase20_rebalance_dates:
            future_candidates = [
                d for d in phase20_rebalance_dates
                if d == date
            ]

            if future_candidates:
                key = (date, model_name)
                if key in target_matrix.index:
                    current_weights = phase20_normalize_weights(
                        target_matrix.loc[key]
                    )

        # Keep the computed gross return available for consistency checks.
        if date in model_daily_results.index:
            reported_gross = model_daily_results.loc[date, "Gross Return"]
            if np.isfinite(reported_gross):
                # A very small discrepancy can arise from missing asset returns.
                # Larger discrepancies are retained for diagnostics below.
                pass

    contribution_df = pd.DataFrame(contribution_records)
    weight_df = pd.DataFrame(weight_records)

    return contribution_df, weight_df


