def save_csv_zstd(
        df,
        filepath,
        compression_level=9,
        index=True,
        **to_csv_kwargs):

    """
    Save a Pandas DataFrame as a Zstandard-compressed CSV.

    Output format:
        filename.csv.zst
    """

    filepath = Path(filepath)

    if filepath.suffix != ".zst":
        filepath = filepath.with_suffix(filepath.suffix + ".zst")

    filepath.parent.mkdir(parents=True, exist_ok=True)

    cctx = zstd.ZstdCompressor(level=compression_level)

    with open(filepath, "wb") as raw_file:

        with cctx.stream_writer(raw_file) as compressed_file:

            # Convert binary Zstandard stream into a text stream
            # for Pandas to_csv().
            with io.TextIOWrapper(
                    compressed_file,
                    encoding="utf-8",
                    newline=""
                    ) as text_file:

                df.to_csv(
                    text_file,
                    index=index,
                    **to_csv_kwargs
                )

    print(f"Saved compressed CSV: {filepath}")

def save_png_pillow(fig, filepath, compress_level=9):
    """
    Save a Matplotlib figure as PNG and recompress it using Pillow.

    compress_level:
        0 = no DEFLATE compression
        9 = maximum DEFLATE compression
    """

    filepath = Path(filepath)
    filepath.parent.mkdir(parents=True, exist_ok=True)

    # Temporary PNG generated by Matplotlib
    with tempfile.NamedTemporaryFile(
            suffix=".png",
            dir=filepath.parent,
            delete=False
            ) as tmp:

        temp_path = Path(tmp.name)

    try:

        # First generate the PNG
        fig.savefig(
            temp_path,
            dpi=300,
            bbox_inches="tight",
            format="png"
        )

        # Recompress/optimize using Pillow
        with Image.open(temp_path) as img:

            # Preserve important PNG modes
            if img.mode not in ("RGB", "RGBA", "L", "LA", "P"):
                img = img.convert("RGBA")

            img.save(
                filepath,
                format="PNG",
                optimize=True,
                compress_level=compress_level
            )

    finally:

        if temp_path.exists():
            temp_path.unlink()

    print(f"Saved compressed PNG: {filepath}")

