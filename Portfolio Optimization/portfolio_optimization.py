def phase17_align_weights(
        weights,
        asset_index,
        model_name):

    weights = pd.Series(
        weights,
        dtype=float
    )

    weights = weights.reindex(
        asset_index
    )

    if weights.isna().any():

        missing_assets = (
            weights[weights.isna()].index.tolist()
        )

        raise ValueError(
            f"{model_name} weights are missing assets: "
            f"{missing_assets}"
        )

    if not np.isfinite(weights.values).all():

        raise ValueError(
            f"{model_name} weights contain "
            "non-finite values."
        )

    weight_sum = weights.sum()

    if weight_sum <= 0:

        raise ValueError(
            f"{model_name} weights have "
            "non-positive total weight."
        )

    if not np.isclose(weight_sum, 1.0):

        weights = weights / weight_sum

    return weights


# --------------------------------------------------------------------------
# Helper: bounded Monte Carlo maximum-Sharpe portfolio
# --------------------------------------------------------------------------

def phase17_monte_carlo_max_sharpe(
        expected_returns_window,
        covariance_window,
        simulations,
        risk_free,
        maximum_weight,
        seed):

    rng = np.random.default_rng(seed)

    n_assets = len(expected_returns_window)

    best_sharpe = -np.inf
    best_weights = None

    batch_size = min(10_000, simulations)

    simulations_remaining = simulations

    while simulations_remaining > 0:

        current_batch = min(
            batch_size,
            simulations_remaining
        )

        weights = rng.dirichlet(
            alpha=np.ones(n_assets),
            size=current_batch
        )

        # Enforce maximum allocation constraint.
        valid = (
            weights.max(axis=1)
            <= maximum_weight + 1e-12
        )

        weights = weights[valid]

        if len(weights) == 0:

            simulations_remaining -= current_batch

            continue

        portfolio_returns = (
            weights @ expected_returns_window.values
        )

        portfolio_variances = np.einsum(
            "ij,jk,ik->i",
            weights,
            covariance_window.values,
            weights
        )

        portfolio_volatility = np.sqrt(
            np.maximum(
                portfolio_variances,
                0.0
            )
        )

        valid_volatility = (
            portfolio_volatility > 0
        )

        if not valid_volatility.any():

            simulations_remaining -= current_batch

            continue

        sharpe = np.full(
            len(weights),
            -np.inf
        )

        sharpe[valid_volatility] = (
            portfolio_returns[valid_volatility]
            - risk_free
        ) / portfolio_volatility[
            valid_volatility
        ]

        local_best_index = np.argmax(sharpe)

        local_best_sharpe = (
            sharpe[local_best_index]
        )

        if local_best_sharpe > best_sharpe:

            best_sharpe = (
                local_best_sharpe
            )

            best_weights = (
                weights[local_best_index]
                .copy()
            )

        simulations_remaining -= current_batch

    if best_weights is None:

        raise RuntimeError(
            "Rolling Monte Carlo optimization "
            "failed to produce a valid portfolio."
        )

    return pd.Series(
        best_weights,
        index=expected_returns_window.index,
        dtype=float
    )


