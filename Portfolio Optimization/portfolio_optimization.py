def get_rebalance_dates(index, frequency=rebalance_frequency):

    index = pd.DatetimeIndex(index)

    if frequency == "Annually":

        dates = (index.to_series().groupby(index.year).first())

    elif frequency == "Quarterly":

        dates = (index.to_series().groupby([index.year,
                                            index.quarter]).first())

    elif frequency == "Monthly":

        dates = (index.to_series().groupby([index.year, index.month]).first())

    else:

        raise ValueError("rebalance_frequency must be "
            "'Annually', 'Quarterly', or 'Monthly'.")

    return pd.DatetimeIndex(dates.values)


def backtest_rebalanced_portfolio(
        target_weights,
        returns,
        initial_capital,
        rebalance_frequency,
        transaction_cost_rate,
        charge_initial_transaction_cost=True):

    # ------------------------------------------------------------
    # Align and validate portfolio weights
    # ------------------------------------------------------------
    target_weights = pd.Series(
        target_weights,
        dtype=float
    ).reindex(returns.columns)

    if target_weights.isna().any():

        missing_assets = target_weights[
            target_weights.isna()
        ].index.tolist()

        raise ValueError(
            "Portfolio weights are missing assets: "
            f"{missing_assets}"
        )

    weight_sum = target_weights.sum()

    if weight_sum <= 0:
        raise ValueError(
            "Portfolio weights must have a positive sum."
        )

    if not np.isclose(weight_sum, 1.0):
        target_weights = (
            target_weights / weight_sum
        )

    # ------------------------------------------------------------
    # Rebalancing dates
    # ------------------------------------------------------------
    rebalance_dates = get_rebalance_dates(
        returns.index,
        frequency=rebalance_frequency
    )

    rebalance_dates = set(rebalance_dates)

    # Avoid charging an annual rebalance on the same date
    # as the initial portfolio construction.
    if len(returns.index) > 0:
        rebalance_dates.discard(returns.index[0])

    # ------------------------------------------------------------
    # Storage
    # ------------------------------------------------------------
    portfolio_value = []
    gross_returns = []
    net_returns = []

    transaction_cost_rates = []
    transaction_cost_dollars_series = []
    turnover_series = []

    # ------------------------------------------------------------
    # Initial portfolio construction
    # ------------------------------------------------------------
    current_weights = target_weights.copy()

    initial_turnover = target_weights.abs().sum()

    if charge_initial_transaction_cost:
        initial_cost_rate = (
            initial_turnover *
            transaction_cost_rate
        )
    else:
        initial_cost_rate = 0.0

    initial_transaction_cost = (
        initial_capital *
        initial_cost_rate
    )

    current_value = (
        initial_capital -
        initial_transaction_cost
    )

    # ------------------------------------------------------------
    # Daily simulation
    # ------------------------------------------------------------
    for date in returns.index:

        daily_asset_returns = returns.loc[date]

        # Gross return before transaction costs
        gross_return = np.dot(
            current_weights.values,
            daily_asset_returns.values
        )

        value_before_trade = (
            current_value *
            (1.0 + gross_return)
        )

        daily_transaction_cost_rate = 0.0
        daily_transaction_cost_dollars = 0.0
        daily_turnover = 0.0

        # --------------------------------------------------------
        # Portfolio drift
        # --------------------------------------------------------
        drifted_values = (
            current_weights *
            (1.0 + daily_asset_returns)
        )

        drifted_total = drifted_values.sum()

        if drifted_total != 0:
            drifted_weights = (
                drifted_values /
                drifted_total
            )
        else:
            drifted_weights = current_weights.copy()

        # --------------------------------------------------------
        # Rebalance
        # --------------------------------------------------------
        if date in rebalance_dates:

            daily_turnover = np.abs(
                target_weights -
                drifted_weights
            ).sum()

            daily_transaction_cost_rate = (
                daily_turnover *
                transaction_cost_rate
            )

            daily_transaction_cost_dollars = (
                value_before_trade *
                daily_transaction_cost_rate
            )

            current_value = (
                value_before_trade -
                daily_transaction_cost_dollars
            )

            current_weights = (
                target_weights.copy()
            )

        else:

            current_value = value_before_trade
            current_weights = drifted_weights

        # --------------------------------------------------------
        # Net daily return
        # --------------------------------------------------------
        previous_value = (
            portfolio_value[-1]
            if portfolio_value
            else initial_capital
        )

        net_return = (
            current_value /
            previous_value
        ) - 1.0

        # --------------------------------------------------------
        # Store
        # --------------------------------------------------------
        portfolio_value.append(current_value)
        gross_returns.append(gross_return)
        net_returns.append(net_return)

        transaction_cost_rates.append(
            daily_transaction_cost_rate
        )

        transaction_cost_dollars_series.append(
            daily_transaction_cost_dollars
        )

        turnover_series.append(
            daily_turnover
        )

    # ------------------------------------------------------------
    # Convert to Series
    # ------------------------------------------------------------
    portfolio_value = pd.Series(
        portfolio_value,
        index=returns.index,
        name="Portfolio Value"
    )

    gross_returns = pd.Series(
        gross_returns,
        index=returns.index,
        name="Gross Returns"
    )

    net_returns = pd.Series(
        net_returns,
        index=returns.index,
        name="Net Returns"
    )

    transaction_cost_rates = pd.Series(
        transaction_cost_rates,
        index=returns.index,
        name="Transaction Cost Rate"
    )

    transaction_cost_dollars = pd.Series(
        transaction_cost_dollars_series,
        index=returns.index,
        name="Transaction Cost ($)"
    )

    turnover_series = pd.Series(
        turnover_series,
        index=returns.index,
        name="Turnover"
    )

    # ------------------------------------------------------------
    # Performance statistics
    # ------------------------------------------------------------
    net_return = (
        (1.0 + net_returns).prod()
        ** (252.0 / len(net_returns))
        - 1.0
    )

    net_volatility = (
        net_returns.std() *
        np.sqrt(252)
    )

    if (
        np.isfinite(net_volatility)
        and net_volatility > 0
    ):
        net_sharpe = (
            (net_return - risk_free_rate) /
            net_volatility
        )
    else:
        net_sharpe = np.nan

    net_cumulative_growth = (
        1.0 + net_returns
    ).cumprod()

    net_running_max = (
        net_cumulative_growth.cummax()
    )

    net_drawdown = (
        net_cumulative_growth /
        net_running_max
    ) - 1.0

    net_max_dd = net_drawdown.min()

    net_downside_returns = (
        net_returns[net_returns < 0]
    )

    if len(net_downside_returns) > 1:

        net_downside_volatility = (
            net_downside_returns.std() *
            np.sqrt(252)
        )

    else:

        net_downside_volatility = np.nan

    if (
        np.isfinite(net_downside_volatility)
        and net_downside_volatility > 0
    ):
        net_sortino = (
            (net_return - risk_free_rate) /
            net_downside_volatility
        )
    else:
        net_sortino = np.nan

    if (
        np.isfinite(net_max_dd)
        and net_max_dd != 0
    ):
        net_calmar = (
            net_return /
            abs(net_max_dd)
        )
    else:
        net_calmar = np.nan

    net_var_95 = np.percentile(
        net_returns,
        5
    )

    net_cvar_95 = (
        net_returns[
            net_returns <= net_var_95
        ].mean()
    )

    # ------------------------------------------------------------
    # Transaction-cost accounting
    # ------------------------------------------------------------
    recurring_transaction_cost = (
        transaction_cost_dollars.sum()
    )

    total_transaction_cost = (
        initial_transaction_cost +
        recurring_transaction_cost
    )

    total_turnover = (
        initial_turnover +
        turnover_series.sum()
    )

    # ------------------------------------------------------------
    # Return
    # ------------------------------------------------------------
    return {

        "target_weights": target_weights,

        "portfolio_value": portfolio_value,

        "gross_returns": gross_returns,
        "net_returns": net_returns,

        "transaction_cost_rates":
            transaction_cost_rates,

        "transaction_cost_dollars":
            transaction_cost_dollars,

        "turnover":
            turnover_series,

        "initial_turnover":
            initial_turnover,

        "initial_transaction_cost_rate":
            initial_cost_rate,

        "initial_transaction_cost":
            initial_transaction_cost,

        "recurring_transaction_cost":
            recurring_transaction_cost,

        "total_transaction_cost":
            total_transaction_cost,

        "total_turnover":
            total_turnover,

        "net_return":
            net_return,

        "net_volatility":
            net_volatility,

        "net_sharpe":
            net_sharpe,

        "net_sortino":
            net_sortino,

        "net_max_dd":
            net_max_dd,

        "net_calmar":
            net_calmar,

        "net_var_95":
            net_var_95,

        "net_cvar_95":
            net_cvar_95
    }


